const UNIQUE = [...new Set(RAW.trim().toUpperCase().split(/\s+/))].filter((word) =>
  /^[A-Z]{5,8}$/.test(word),
);

export const WORDS = Object.freeze(UNIQUE.sort());

export const WORDS_BY_LENGTH = Object.freeze(
  [5, 6, 7, 8].reduce((acc, length) => {
    acc[length] = Object.freeze(WORDS.filter((word) => word.length === length));
    return acc;
  }, {}),
);

export function wordPool(length) {
  return WORDS_BY_LENGTH[length] ?? [];
}
